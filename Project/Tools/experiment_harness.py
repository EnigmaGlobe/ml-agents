"""
Experiment harness generator for PushBlock parameter sweep.

Generates a master CSV listing all 27 (3x3x3) combinations of
`block_mass`, `block_size`, and `surface_friction` levels (Low/Medium/High),
and creates a Windows batch file per run that starts `mlagents-learn` with
the corresponding run-id. The generated batch files include placeholders
for how to supply environment parameter overrides from the Python side
or via trainer config/side-channel.

Usage: python experiment_harness.py --outdir ../results --config config/ppo/your_config.yaml --env PATH_TO_ENV_BUILD

Note: This tool does NOT itself change Unity scene files or Inspector values.
It only creates run metadata and starter scripts. Adjust the generated
commands to match your local `mlagents-learn` invocation and trainer config.
"""
import os
import csv
import argparse
from itertools import product


LEVELS = ["Low", "Medium", "High"]


def make_run_id(mass, size, fric):
    return f"PushBlock_mass-{mass[0]}_size-{size[0]}_fric-{fric[0]}"


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--outdir", default="results", help="Directory to write master CSV and scripts")
    p.add_argument("--config", required=True, help="Path to trainer config YAML for mlagents-learn")
    p.add_argument("--env", required=True, help="Path to Unity environment or leave empty to use the Editor")
    p.add_argument("--base-port", default="5004", help="Base port for communicator (change per parallel run)")
    p.add_argument("--execute", action="store_true", help="If set, execute each generated command serially and record metadata")
    p.add_argument("--cmd-template", default=None, help="Optional command template. Use placeholders: {config},{run_id},{env},{base_port},{mass},{size},{friction}")
    p.add_argument("--sleep-between", type=int, default=0, help="Seconds to sleep between runs when --execute is used")
    args = p.parse_args()

    outdir = os.path.abspath(args.outdir)
    os.makedirs(outdir, exist_ok=True)

    master_csv = os.path.join(outdir, "master_runs.csv")
    bat_dir = os.path.join(outdir, "run_scripts")
    os.makedirs(bat_dir, exist_ok=True)

    rows = []
    for mass, size, fric in product(LEVELS, repeat=3):
        run_id = make_run_id(mass, size, fric)
        rows.append({"run_id": run_id, "mass": mass, "size": size, "friction": fric})

    # Write master CSV
    with open(master_csv, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=["run_id", "mass", "size", "friction"])
        writer.writeheader()
        for r in rows:
            writer.writerow(r)

    # Create a .bat file for each run. User should edit the command to match their env.
    for r in rows:
        run_id = r["run_id"]
        bat_path = os.path.join(bat_dir, f"{run_id}.bat")
        with open(bat_path, "w", encoding="utf-8") as bf:
            bf.write("@echo off\n")
            bf.write("REM Edit the command below to match your mlagents-learn invocation and environment build.\n")
            bf.write("REM This file was auto-generated by experiment_harness.py\n\n")
            # Build a templated command; allow user override via --cmd-template
            if args.cmd_template:
                cmd = args.cmd_template.format(
                    config=args.config,
                    run_id=run_id,
                    env=args.env,
                    base_port=args.base_port,
                    mass=r["mass"],
                    size=r["size"],
                    friction=r["friction"],
                )
            else:
                cmd = (
                    f"mlagents-learn {args.config} --run-id={run_id} --base-port={args.base_port} --env=\"{args.env}\" --train"
                )
            bf.write(cmd + "\n")
            bf.write("REM To pass EnvironmentParameters dynamically you can use a Python side-channel or trainer config.\n")
            bf.write("REM See ML-Agents docs for EnvironmentParameters and SideChannels.\n")

    print(f"Wrote master CSV: {master_csv}")
    print(f"Wrote {len(rows)} run scripts to: {bat_dir}")

    # If --execute was passed, run each command serially and augment master CSV with results.
    if args.execute:
        import subprocess, time, datetime
        results = []
        for r in rows:
            run_id = r["run_id"]
            if args.cmd_template:
                cmd = args.cmd_template.format(
                    config=args.config,
                    run_id=run_id,
                    env=args.env,
                    base_port=args.base_port,
                    mass=r["mass"],
                    size=r["size"],
                    friction=r["friction"],
                )
            else:
                cmd = f"mlagents-learn {args.config} --run-id={run_id} --base-port={args.base_port} --env=\"{args.env}\" --train"

            print(f"Starting run {run_id}: {cmd}")
            start = datetime.datetime.utcnow().isoformat()
            try:
                proc = subprocess.run(cmd, shell=True, capture_output=True, text=True)
                exit_code = proc.returncode
                stdout = proc.stdout[-1000:]
                stderr = proc.stderr[-1000:]
            except Exception as e:
                exit_code = -1
                stdout = ""
                stderr = str(e)
            end = datetime.datetime.utcnow().isoformat()

            results.append({
                "run_id": run_id,
                "mass": r["mass"],
                "size": r["size"],
                "friction": r["friction"],
                "start_time": start,
                "end_time": end,
                "exit_code": exit_code,
                "stdout_tail": stdout.replace('\n','\\n'),
                "stderr_tail": stderr.replace('\n','\\n'),
            })

            # Optional sleep between runs
            if args.sleep_between > 0:
                time.sleep(args.sleep_between)

        # Write augmented master CSV with results
        out_master_with_results = os.path.join(outdir, "master_runs_with_results.csv")
        with open(out_master_with_results, "w", newline="", encoding="utf-8") as f:
            fieldnames = ["run_id", "mass", "size", "friction", "start_time", "end_time", "exit_code", "stdout_tail", "stderr_tail"]
            writer = csv.DictWriter(f, fieldnames=fieldnames)
            writer.writeheader()
            for rr in results:
                writer.writerow(rr)

        print(f"Execution finished. Results written to {out_master_with_results}")


if __name__ == '__main__':
    main()
